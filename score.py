"""Score robotics accounts for Reactor's Remote Policy API.

Reads data/accounts.csv, computes a fit score per account, and writes:
  out/ranked.csv     ranked accounts with every sub-score
  out/pipeline.md    a readable pipeline grouped by metro

Each input signal is a 0-3 judgment recorded in the CSV with its sources,
so anyone can disagree with a number and rerun.

Usage:
  python score.py
  python score.py --weights offboard=3 lockin=-2
"""

import argparse
import csv
import math
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).parent

# Why these weights: Reactor only has to win on serving when a team already
# runs its policy off the robot (offboard) and runs a model Reactor can host
# (model_match). Latency fit and robot-hours decide whether a deal is winnable
# today and whether it fills a server. Lock-in to another model API is a drag.
DEFAULT_WEIGHTS = {
    "offboard": 2.0,      # already runs inference off-robot or is cloud-connected
    "model_match": 2.0,   # runs a Reactor-hosted model, or an open/own model for Serve
    "latency_fit": 1.5,   # core task tolerates network + standard-tier latency
    "robot_hours": 1.5,   # fleet size x hours per day (fills servers)
    "density": 1.0,       # other targets in the same metro share regional capacity
    "warmth": 1.0,        # existing touchpoint with Reactor or Abdullah
    "lockin": -1.5,       # policy served through another provider's API
}

SIGNALS = ["offboard", "model_match", "latency_fit", "robot_hours", "warmth", "lockin"]


def density_scores(rows):
    """3 if 5+ targets share the metro, 2 if 2-4, 1 if alone, 0 if unknown."""
    counts = Counter(r["metro"] for r in rows if r["metro"])
    out = {}
    for r in rows:
        n = counts.get(r["metro"], 0)
        out[r["account"]] = 0 if not r["metro"] else 3 if n >= 5 else 2 if n >= 2 else 1
    return out, counts


def score(rows, weights):
    dens, counts = density_scores(rows)
    max_score = sum(3 * w for w in weights.values() if w > 0)
    ranked = []
    for r in rows:
        s = {k: int(r[k]) for k in SIGNALS}
        s["density"] = dens[r["account"]]
        raw = sum(weights[k] * s[k] for k in weights)
        ranked.append({**r, **{f"s_{k}": v for k, v in s.items()},
                       "score": round(100 * max(raw, 0) / max_score)})
    ranked.sort(key=lambda x: (-x["score"], x["account"]))
    for i, r in enumerate(ranked, 1):
        r["rank"] = i
    return ranked, counts


def write_outputs(ranked, counts):
    out = ROOT / "out"
    out.mkdir(exist_ok=True)
    cols = ["rank", "score", "account", "segment", "metro", "first_call",
            "first_call_title", "contact_email", "email_status", "contact_status", "why_now"] + \
           [f"s_{k}" for k in SIGNALS + ["density"]] + ["evidence_1", "evidence_2"]
    with open(out / "ranked.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols, extrasaction="ignore")
        w.writeheader()
        w.writerows(ranked)

    lines = ["# Reactor robotics pipeline (generated by score.py)", ""]
    lines.append("Metros by number of targets: " + ", ".join(
        f"{m} ({n})" for m, n in counts.most_common()) + ".")
    lines.append("")
    lines.append("| # | Score | Account | Segment | Metro | First call | Why now |")
    lines.append("|---|---|---|---|---|---|---|")
    for r in ranked:
        who = f"{r['first_call']}, {r['first_call_title']}" if r["first_call"] else "(open)"
        lines.append(f"| {r['rank']} | {r['score']} | {r['account']} | {r['segment']} | "
                     f"{r['metro'] or 'n/a'} | {who} | {r['why_now']} |")
    (out / "pipeline.md").write_text("\n".join(lines) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--weights", nargs="*", default=[],
                    help="override weights, e.g. offboard=3 lockin=-2")
    args = ap.parse_args()
    weights = dict(DEFAULT_WEIGHTS)
    for kv in args.weights:
        k, v = kv.split("=")
        if k not in weights:
            raise SystemExit(f"unknown weight {k}; choose from {list(weights)}")
        weights[k] = float(v)

    with open(ROOT / "data" / "accounts.csv", newline="") as f:
        rows = list(csv.DictReader(f))
    ranked, counts = score(rows, weights)
    write_outputs(ranked, counts)
    width = max(len(r["account"]) for r in ranked)
    for r in ranked:
        print(f"{r['rank']:>2}  {r['score']:>3}  {r['account']:<{width}}  {r['metro'] or 'n/a'}")


if __name__ == "__main__":
    main()
